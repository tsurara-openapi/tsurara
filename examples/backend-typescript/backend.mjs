// An external tsurara backend in JavaScript (design.md 18.11). It declares Go's
// capabilities and a Go-like naming policy, so `generate` receives the model lowered to `tir`
// (unions only as declarations, no intersections, inline records or inheritance) and the names tsurara
// allocated for it. It writes one Go-like text file per declaration.
//
//   language: { command: [node, examples/backend-typescript/backend.mjs] }

const MARKER = '// Generated by the example backend. Do not edit.';

const pascal = (casing, rest = {}) => ({
  case: casing,
  digitPrefix: 'V',
  upperPrefix: 'X',
  fallback: 'Value',
  ...rest,
});

const describe = {
  protocol: 2,
  semVersions: [1],
  markers: { generated: MARKER },
  lowering: {
    capabilities: {
      inlineRecords: false,
      structuralUnions: false,
      taggedUnions: true,
      intersections: false,
      inheritance: 'none',
      literalTypes: false,
      enums: 'none',
      tuples: false,
      strictDecoding: false,
      nullablePrimitives: true,
      recursionByValue: false,
    },
  },
  naming: {
    contexts: {
      type: pascal('pascal'),
      function: pascal('pascal'),
      member: pascal('pascal', {
        reserved: ['MarshalJSON', 'UnmarshalJSON'],
        reservedSuffix: 'Field',
      }),
      constant: pascal('pascal', { fallback: 'Empty' }),
      file: { case: 'snake', digitPrefix: '', fallback: 'value', ascii: true },
    },
    initialisms: ['API', 'HTTP', 'ID', 'JSON', 'URL', 'UUID'],
  },
};

/** Writes a type expression of `tir`. */
const type = (e, names) => {
  if (typeof e === 'string')
    return { any: 'any', never: 'any', null: 'any', bool: 'bool', bytes: '[]byte' }[e] ?? e;
  if ('named' in e) return names.decls[e.named.decl].name;
  if ('list' in e) return `[]${type(e.list, names)}`;
  if ('map' in e) return `map[string]${type(e.map, names)}`;
  if ('nullable' in e) return `*${type(e.nullable, names)}`;
  if ('scalar' in e) return JSON.stringify(e.scalar);
  if ('external' in e) return type(e.external.schema, names);
  // Structural unions, intersections and inline records do not reach a backend with these
  // capabilities.
  throw new Error(`unexpected type ${JSON.stringify(e)}`);
};

// `EXAMPLE_NAMING_BUG=1` ignores the allocated names and converts the preferred names itself
// without handling collisions (`pet-status` and `pet_status` both become `PetStatus`), to see
// `tsurara test-backend` fail.
const buggy = process.env.EXAMPLE_NAMING_BUG === '1';
const naivePascal = (s) =>
  s
    .split(/[^A-Za-z0-9]+/)
    .filter((w) => w !== '')
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join('');

const generate = ({ lowered, names: allocated }) => {
  const names = buggy
    ? {
        ...allocated,
        decls: allocated.decls.map((d, i) => ({
          ...d,
          name: naivePascal(lowered.decls[i].preferredName),
        })),
      }
    : allocated;
  const files = lowered.decls.map((decl, i) => {
    const n = names.decls[i];
    const [kind, body] = Object.entries(decl.kind)[0];
    let code = `${MARKER}\n\n`;
    if (kind === 'record') {
      if (body.base != null) throw new Error('inheritance does not reach this backend');
      code += `type ${n.name} struct {\n`;
      body.fields.forEach((f, j) => {
        code += `\t${n.members[j]} ${type(f.ty, names)} \`json:${JSON.stringify(f.wireName)}\`\n`;
      });
      code += '}\n';
    } else if (kind === 'enum') {
      code += `type ${n.name} string // ${n.members.join(', ')}\n`;
    } else if (kind === 'alias') {
      code += `type ${n.name} = ${type(body, names)}\n`;
    } else if (kind === 'taggedUnion') {
      code += `type ${n.name} struct{ Value any } // tagged by ${JSON.stringify(body.property)}\n`;
    } else if (kind === 'untaggedUnion') {
      // A declared wrapper; union expressions themselves are gone.
      code += `type ${n.name} struct{ Value any } // one of ${body.members.map((m) => type(m, names)).join(', ')}\n`;
    } else {
      throw new Error(`unexpected declaration ${kind}`);
    }
    return { path: `${n.file}.go.txt`, contents: code };
  });
  return { files, warnings: [] };
};

const [mode] = process.argv.slice(2);
if (mode === 'describe') {
  process.stdout.write(JSON.stringify(describe));
} else if (mode === 'generate') {
  let input = '';
  process.stdin.on('data', (c) => (input += c));
  process.stdin.on('end', () => process.stdout.write(JSON.stringify(generate(JSON.parse(input)))));
} else {
  process.stderr.write('usage: backend.mjs describe|generate\n');
  process.exit(2);
}
