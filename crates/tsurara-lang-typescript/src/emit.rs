/// Line placed at the top of every generated file. Used to recognize stale generated files.
pub const HEADER: &str = "// Generated by tsurara. Do not edit.";

/// Prefix of the line in index.ts that states the required `@tsurara/client` version range.
pub const CLIENT_RANGE_PREFIX: &str = "// @tsurara/client ";

/// A group of declarations. The unit assigned to a file.
#[derive(Debug, Default, Clone)]
pub(crate) struct Unit {
    pub(crate) code: String,
    /// Declared names.
    pub(crate) declares: Vec<String>,
    /// Named types it references.
    pub(crate) refs: BTreeSet<String>,
    /// Values it references (OperationDefs and so on).
    pub(crate) value_refs: BTreeSet<String>,
    pub(crate) externals: BTreeSet<Import>,
    /// Types imported from `@tsurara/client`.
    pub(crate) client_types: BTreeSet<&'static str>,
    /// Values imported from `@tsurara/client`.
    pub(crate) client_values: BTreeSet<&'static str>,
    pub(crate) has_values: bool,
}

impl Unit {
    pub(crate) fn use_type(&mut self, ty: &Type) {
        let mut refs = Vec::new();
        ty.collect_refs(&mut refs);
        self.refs.extend(refs.into_iter().map(str::to_owned));
        let mut imports = Vec::new();
        ty.collect_imports(&mut imports);
        self.externals.extend(imports.into_iter().cloned());
    }

    pub(crate) fn alias(&mut self, name: &str, ty: &Type, doc: Option<&Doc>) {
        self.use_type(ty);
        self.declares.push(name.to_owned());
        if !self.code.is_empty() {
            self.code.push('\n');
        }
        self.code.push_str(&print_type_alias(name, ty, doc));
    }

    pub(crate) fn raw(&mut self, code: &str) {
        if !self.code.is_empty() {
            self.code.push('\n');
        }
        self.code.push_str(code);
    }
}

pub fn emit(
    model: &Model,
    common: &tsurara_sem::Options,
    opts: &Options,
) -> (Vec<OutputFile>, Vec<tsurara_sem::Warning>, Manifest) {
    // `enumStyle: const` needs the enum nodes, which the lowering replaces with literal unions.
    let enums: BTreeMap<tsurara_sem::naming::NameId, tsurara_sem::ir::Enum> = model
        .schemas
        .iter()
        .filter_map(|d| match &d.ty {
            Type::Enum(e) => Some((d.id, e.clone())),
            // `nullable: true` next to `enum` (3.0).
            Type::Union(ts) => match ts.as_slice() {
                [Type::Enum(e), Type::Null] => Some((
                    d.id,
                    tsurara_sem::ir::Enum {
                        nullable: true,
                        ..e.clone()
                    },
                )),
                _ => None,
            },
            _ => None,
        })
        .collect();
    let (lowered, mut warnings) = crate::lower::lower_model(model, common, opts);
    let original = model;
    let model = &lowered;
    let mut files: BTreeMap<String, Vec<Unit>> = BTreeMap::new();

    // Schemas. The original type and its Writable type go in the same file.
    let mut schema_files: BTreeMap<String, String> = BTreeMap::new();
    let mut by_loc: Vec<(String, Vec<&TypeDecl>)> = Vec::new();
    for decl in &model.schemas {
        let key = decl.loc.to_string();
        match by_loc.iter_mut().find(|(k, _)| *k == key) {
            Some((_, v)) => v.push(decl),
            None => by_loc.push((key, vec![decl])),
        }
    }
    for (_, decls) in &by_loc {
        let base = decls.iter().find(|d| !d.writable).unwrap_or(&decls[0]);
        let path = match opts.layout {
            Layout::Single => "index.ts".to_owned(),
            _ => format!("schemas/{}.ts", base.name),
        };
        let mut unit = Unit::default();
        for d in decls
            .iter()
            .filter(|d| !d.writable)
            .chain(decls.iter().filter(|d| d.writable))
        {
            schema_unit(&mut unit, d, enums.get(&d.id), opts);
            schema_files.insert(d.name.clone(), path.clone());
        }
        files.entry(path).or_default().push(unit);
    }

    let mut manifest = Manifest::new("typescript");
    manifest.types = model
        .schemas
        .iter()
        .map(|d| TypeEntry {
            name: d.id,
            export: Export::new(&d.name, &schema_files[&d.name]),
        })
        .collect();

    // Operations.
    let tag_files = tag_file_names(&model.operations);
    let mut value_files: BTreeMap<String, String> = BTreeMap::new();
    let mut operation_files: Vec<String> = Vec::new();
    for op in &model.operations {
        let path = match opts.layout {
            Layout::Single => "index.ts".to_owned(),
            Layout::Split => format!("operations/{}.ts", op.name),
            Layout::Tags => format!(
                "operations/{}.ts",
                tag_files
                    .get(op.tags.first().map(String::as_str).unwrap_or(""))
                    .expect("every tag has a file")
            ),
        };
        operation_files.push(path.clone());
        let unit = operation_unit(op);
        manifest.operations.push(manifest_operation(
            op,
            OperationKind::Operation,
            &unit,
            &path,
        ));
        for n in &unit.declares {
            schema_files.insert(n.clone(), path.clone());
            value_files.insert(n.clone(), path.clone());
        }
        files.entry(path).or_default().push(unit);
    }
    for hook in &model.webhooks {
        let path = match opts.layout {
            Layout::Single => "index.ts".to_owned(),
            _ => format!("webhooks/{}.ts", hook.name),
        };
        let unit = message_unit(hook, "Webhook");
        manifest.operations.push(manifest_operation(
            hook,
            OperationKind::Webhook,
            &unit,
            &path,
        ));
        for n in &unit.declares {
            schema_files.insert(n.clone(), path.clone());
        }
        files.entry(path).or_default().push(unit);
    }

    let client_path = match opts.layout {
        Layout::Single => "index.ts".to_owned(),
        _ => "client.ts".to_owned(),
    };
    // Without operations the output is types only and mentions nothing of the client.
    if common.operations {
        files
            .entry(client_path.clone())
            .or_default()
            .push(client_unit(&model.servers, &model.security_schemes));
    }

    if opts.aggregate_maps && opts.layout != Layout::Single {
        files
            .entry("operations.ts".to_owned())
            .or_default()
            .push(operations_map_unit(&model.operations));
        files
            .entry("paths.ts".to_owned())
            .or_default()
            .push(paths_map_unit(&model.operations));
    } else if opts.aggregate_maps {
        let mut units = vec![
            operations_map_unit(&model.operations),
            paths_map_unit(&model.operations),
        ];
        files
            .entry("index.ts".to_owned())
            .or_default()
            .append(&mut units);
    }

    let mut out: Vec<OutputFile> = files
        .iter()
        .map(|(path, units)| OutputFile {
            path: path.clone(),
            contents: render_file(path, units, &schema_files, &value_files, opts),
        })
        .collect();

    if opts.layout != Layout::Single {
        // The runtime version marker: call functions and channel decoders use the runtime; the
        // types alone do not.
        let barrel = barrel(
            &files,
            opts,
            common.operations || !model.channels.is_empty(),
        );
        out.push(OutputFile {
            path: "index.ts".to_owned(),
            contents: barrel,
        });
    } else if let Some(index) = out
        .iter_mut()
        .find(|f| f.path == "index.ts" && (common.operations || !model.channels.is_empty()))
    {
        index.contents = index.contents.replacen(
            &format!("{HEADER}\n"),
            &format!(
                "{HEADER}\n{CLIENT_RANGE_PREFIX}{}\n",
                opts.client_version_range
            ),
            1,
        );
    }
    // Event channels, outside the barrel like the query and Zod files.
    for c in &model.channels {
        let path = format!("channels/{}.ts", c.ident);
        let unit = channel_unit(c, &mut warnings);
        out.push(OutputFile {
            contents: render_file(&path, &[unit], &schema_files, &BTreeMap::new(), opts),
            path,
        });
    }
    if opts.validators == Some(crate::options::Validators::Zod) {
        out.extend(crate::zod::emit(
            original,
            model,
            opts,
            common.operations,
            &mut warnings,
        ));
    }
    let mut helpers: crate::query::Helpers = Vec::new();
    if opts.query.is_some() {
        let (files, query_helpers) =
            crate::query::emit(model, &operation_files, opts, &mut warnings);
        out.extend(files);
        helpers.extend(query_helpers);
    }
    if opts.mocks.is_some() {
        for op in &model.operations {
            helpers.push((
                op.id.clone(),
                vec![(
                    "mockHandler",
                    format!("{}Handler", op.name),
                    format!("mocks/operations/{}.ts", op.name),
                )],
            ));
        }
    }
    // The helpers of each operation in the manifest.
    for (id, roles) in helpers {
        if let Some(entry) = manifest
            .operations
            .iter_mut()
            .find(|e| e.operation_id == id && e.kind == OperationKind::Operation)
        {
            for (role, name, path) in roles {
                entry
                    .helpers
                    .insert(role.to_owned(), Export::new(&name, &path));
            }
        }
    }
    if let Some(mocks) = opts.mocks {
        out.extend(crate::mocks::emit(
            original,
            model,
            &operation_files,
            &schema_files,
            mocks,
            opts,
        ));
    }
    out.sort_by(|a, b| a.path.cmp(&b.path));
    if common.runtime == tsurara_sem::RuntimeSource::Vendor {
        crate::vendor::vendor(&mut out, opts);
    }
    (out, warnings, manifest)
}

/// The manifest entry of an operation or webhook emitted as `unit` into `path`.
fn manifest_operation(
    op: &Operation,
    kind: OperationKind,
    unit: &Unit,
    path: &str,
) -> OperationEntry {
    let declared = |name: &str| unit.declares.iter().any(|d| d == name);
    let mut types = BTreeMap::new();
    let mut operation_def = None;
    for (template, name) in &op.type_names {
        if !declared(name) {
            continue;
        }
        if template == "{}Def" {
            operation_def = Some(Export::new(name, path));
            continue;
        }
        let role = template
            .trim_start_matches("{P}")
            .trim_start_matches("Webhook")
            .trim_start_matches("Callback");
        let mut chars = role.chars();
        let role = match chars.next() {
            Some(c) => c.to_lowercase().chain(chars).collect(),
            None => continue,
        };
        types.insert(role, Export::new(name, path));
    }
    OperationEntry {
        helpers: Default::default(),
        operation_id: op.id.clone(),
        kind,
        function: (kind == OperationKind::Operation && declared(&op.name))
            .then(|| Export::new(&op.name, path)),
        operation_def,
        types,
    }
}

/// The file of an event channel: the message type, the topic parameters and builder, the
/// channel definition and the decoder.
fn channel_unit(
    c: &tsurara_sem::operation::Channel,
    warnings: &mut Vec<tsurara_sem::Warning>,
) -> Unit {
    let mut unit = Unit::default();
    let derived = |template: &str| {
        c.type_names
            .get(template)
            .unwrap_or_else(|| panic!("channel {} has no name for {template}", c.name))
            .clone()
    };
    let message = derived("{P}Message");
    let params = derived("{P}TopicParams");
    let json = c
        .contents
        .iter()
        .find(|m| matches!(m.body_kind, BodyKind::Json | BodyKind::Auto));
    let text = c.contents.iter().find(|m| m.body_kind == BodyKind::Text);
    let (ty, parse_as) = match (json, text) {
        (Some(m), _) => (m.ty.clone(), "json"),
        (None, Some(_)) => (Type::String, "text"),
        (None, None) => {
            if !c.contents.is_empty() {
                warnings.push(tsurara_sem::Warning {
                    kind: tsurara_sem::WarningKind::Unsupported,
                    loc: c.loc.join("content"),
                    message: format!(
                        "channel `{}` has no JSON or text payload; its messages are decoded as JSON of an unknown type",
                        c.name
                    ),
                    language: None,
                });
            }
            (Type::Unknown, "json")
        }
    };
    unit.alias(&message, &ty, c.doc.as_ref());
    let topic = format!("{}Topic", c.ident);
    let decode = {
        let mut chars = c.ident.chars();
        let pascal: String = chars
            .next()
            .map(|f| f.to_uppercase().chain(chars).collect())
            .unwrap_or_default();
        format!("decode{pascal}")
    };
    let id = string_literal(&c.name);
    let template = string_literal(&c.channel);
    // The topic: literal parts escaped for a template literal, each variable percent-encoded.
    let mut literal = String::from("`");
    let mut rest = c.channel.as_str();
    // Text since the last variable; `{}` is not a variable (as in the model's `template_variables`).
    let mut text = String::new();
    while let Some(start) = rest.find('{') {
        let Some(end) = rest[start..].find('}') else {
            break;
        };
        let name = &rest[start + 1..start + end];
        if name.is_empty() {
            text.push_str(&rest[..start + end + 1]);
            rest = &rest[start + end + 1..];
            continue;
        }
        text.push_str(&rest[..start]);
        literal.push_str(&template_text(&std::mem::take(&mut text)));
        let access = if is_identifier(name) {
            format!("params.{name}")
        } else {
            format!("params[{}]", string_literal(name))
        };
        write!(literal, "${{encodeURIComponent(String({access}))}}").unwrap();
        rest = &rest[start + end + 1..];
    }
    text.push_str(rest);
    literal.push_str(&template_text(&text));
    literal.push('`');
    let topic_fn = if c.parameters.is_empty() {
        format!(
            "/** The topic relative to the deployment's prefix: `{}`. */\nexport function {topic}(): string {{\n  return {literal};\n}}\n",
            doc_inline(&c.channel)
        )
    } else {
        let params_ty = Type::Object(Object {
            properties: c
                .parameters
                .iter()
                .map(|p| Property::new(p.name.clone(), p.ty.clone()))
                .collect(),
            index: None,
        });
        let doc = Doc {
            description: Some(format!("The parameters of the topic `{}`.", c.channel)),
            tags: Vec::new(),
        };
        unit.alias(&params, &params_ty, Some(&doc));
        format!(
            "/** The topic relative to the deployment's prefix: `{}`, with each parameter percent-encoded. */\nexport function {topic}(params: {params}): string {{\n  return {literal};\n}}\n",
            doc_inline(&c.channel)
        )
    };
    unit.raw(&topic_fn);
    unit.raw(&format!(
        "export const {}ChannelDef = {{\n  v: 1,\n  id: {id},\n  channel: {template},\n  parseAs: '{parse_as}',\n}} as const;\n",
        c.ident
    ));
    unit.raw(&format!(
        "/** Decodes the text of one message of `{}` (`MessageEvent.data`). Validates it with `options.validate`. */\nexport function {decode}(data: string, options?: DecodeOptions): MessageResult<{message}> {{\n  return decodeMessage<{message}>({}ChannelDef, data, options);\n}}\n",
        doc_inline(&c.name), c.ident
    ));
    unit.declares.push(topic);
    unit.declares.push(decode);
    unit.declares.push(format!("{}ChannelDef", c.ident));
    unit.client_types.insert("DecodeOptions");
    unit.client_types.insert("MessageResult");
    unit.client_values.insert("decodeMessage");
    unit.has_values = true;
    unit
}

/// `s` as the text of a template literal.
fn template_text(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('`', "\\`")
        .replace("${", "\\${")
}

fn is_identifier(s: &str) -> bool {
    let mut chars = s.chars();
    chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
}

fn schema_unit(
    unit: &mut Unit,
    decl: &TypeDecl,
    enum_node: Option<&tsurara_sem::ir::Enum>,
    opts: &Options,
) {
    if opts.enum_style == EnumStyle::Const {
        if let Some((values, keys, nullable)) = enum_node.and_then(enum_values) {
            let mut code = String::new();
            if let Some(doc) = &decl.doc {
                code.push_str(&print_doc(doc, 0));
            }
            writeln!(code, "export const {} = {{", decl.name).unwrap();
            for (v, key) in values.iter().zip(&keys) {
                let value = match v {
                    Literal::String(s) => string_literal(s),
                    Literal::Number(n) => n.to_string(),
                    Literal::Boolean(b) => b.to_string(),
                };
                writeln!(code, "  {}: {value},", property_key(key)).unwrap();
            }
            writeln!(code, "}} as const;").unwrap();
            let null = if nullable { " | null" } else { "" };
            writeln!(
                code,
                "export type {0} = (typeof {0})[keyof typeof {0}]{null};",
                decl.name
            )
            .unwrap();
            unit.declares.push(decl.name.clone());
            unit.has_values = true;
            unit.raw(&code);
            return;
        }
    }
    unit.alias(&decl.name, &decl.ty, decl.doc.as_ref());
}

/// The values of an enum that can be an `as const` object (strings and numbers with distinct keys),
/// with their keys: the member names of the definition (`x-enum-varnames`), or the values.
fn enum_values(e: &tsurara_sem::ir::Enum) -> Option<(Vec<Literal>, Vec<String>, bool)> {
    let mut values = Vec::new();
    let mut keys = Vec::new();
    for (i, v) in e.values.iter().enumerate() {
        let key = match v {
            Literal::String(s) => s.clone(),
            Literal::Number(n) => n.to_string(),
            Literal::Boolean(_) => return None,
        };
        values.push(v.clone());
        keys.push(e.names.get(i).cloned().unwrap_or(key));
    }
    let distinct: BTreeSet<&String> = keys.iter().collect();
    (!values.is_empty() && distinct.len() == keys.len()).then_some((values, keys, e.nullable))
}

/// File name per tag. Operations without tags go in `default`.
fn tag_file_names(ops: &[Operation]) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    let mut taken: BTreeSet<String> = BTreeSet::new();
    for op in ops {
        let tag = op.tags.first().cloned().unwrap_or_default();
        if out.contains_key(&tag) {
            continue;
        }
        let base = if tag.is_empty() {
            "default".to_owned()
        } else {
            let c = names::camel_case(&tag);
            if c.is_empty() { "tag".to_owned() } else { c }
        };
        let mut name = base.clone();
        let mut n = 2;
        while taken.contains(&name.to_lowercase()) {
            name = format!("{base}{n}");
            n += 1;
        }
        taken.insert(name.to_lowercase());
        out.insert(tag, name);
    }
    out
}

fn group_object(params: &[&Param]) -> Type {
    Type::Object(Object {
        properties: params
            .iter()
            .map(|p| {
                Property::new(p.name.clone(), p.ty.clone())
                    .optional(!p.required)
                    .with_doc(p.doc.clone())
            })
            .collect(),
        index: None,
    })
}

/// The `Data` type.
fn data_type(op: &Operation) -> Type {
    let mut props = Vec::new();
    for location in [
        ParamIn::Path,
        ParamIn::Query,
        ParamIn::Header,
        ParamIn::Cookie,
    ] {
        let ps: Vec<&Param> = op
            .params
            .iter()
            .filter(|p| p.location == location)
            .collect();
        if ps.is_empty() {
            continue;
        }
        let required = ps.iter().any(|p| p.required);
        props.push(Property::new(location.group(), group_object(&ps)).optional(!required));
    }
    if let Some(qs) = op
        .params
        .iter()
        .find(|p| p.location == ParamIn::QueryString)
    {
        props.push(
            Property::new("querystring", qs.ty.clone())
                .optional(!qs.required)
                .with_doc(qs.doc.clone()),
        );
    }
    let mut variants = None;
    if let Some(body) = &op.body {
        if body.contents.len() == 1 {
            props.push(
                Property::new("body", body.contents[0].ty.clone())
                    .optional(!body.required)
                    .with_doc(body.doc.clone()),
            );
        } else if body.contents.len() > 1 {
            // One member per media type, so that `body` is checked against `contentType`. Only the
            // first media type, which the runtime uses by default, may omit `contentType`.
            let members = body
                .contents
                .iter()
                .enumerate()
                .map(|(i, c)| {
                    Type::Object(Object {
                        properties: vec![
                            Property::new(
                                "contentType",
                                Type::string_literal(c.media_type.clone()),
                            )
                            .optional(i == 0),
                            Property::new("body", c.ty.clone())
                                .optional(!body.required)
                                .with_doc(body.doc.clone()),
                        ],
                        index: None,
                    })
                })
                .collect();
            variants = Some(Type::Union(members));
        }
    }
    let common = Type::Object(Object {
        properties: props,
        index: None,
    });
    match variants {
        None => common,
        Some(v) if is_empty_object(&common) => v,
        Some(v) => Type::Intersection(vec![common, v]),
    }
}

fn is_empty_object(ty: &Type) -> bool {
    matches!(ty, Type::Object(o) if o.properties.is_empty() && o.index.is_none())
}

fn status_map(responses: &[&Response]) -> Type {
    Type::Object(Object {
        properties: responses
            .iter()
            .map(|r| Property::new(r.status.key(), r.data_type()))
            .collect(),
        index: None,
    })
}

fn result_member(fields: Vec<(&str, Type)>) -> Type {
    Type::Object(Object {
        properties: fields
            .into_iter()
            .map(|(k, t)| Property::new(k, t))
            .collect(),
        index: None,
    })
}

fn status_type(s: Status) -> Type {
    match s {
        Status::Code(c) => Type::Literal(Literal::Number(c.into())),
        _ => Type::Number,
    }
}

/// Builds the `Result` type as an expanded union (design.md 8.2).
fn result_type(op: &Operation) -> Type {
    let response = || Type::builtin("Response");
    let mut members = Vec::new();
    let successes: Vec<&Response> = op
        .responses
        .iter()
        .filter(|r| r.status.is_success() == Some(true))
        .collect();
    let default = op.responses.iter().find(|r| r.status == Status::Default);
    for r in &successes {
        members.push(result_member(vec![
            ("ok", Type::Literal(Literal::Boolean(true))),
            ("kind", Type::string_literal("success")),
            ("status", status_type(r.status)),
            ("data", r.data_type()),
            ("response", response()),
        ]));
    }
    if successes.is_empty() {
        if let Some(d) = default {
            members.push(result_member(vec![
                ("ok", Type::Literal(Literal::Boolean(true))),
                ("kind", Type::string_literal("success")),
                ("status", Type::Number),
                ("data", d.data_type()),
                ("response", response()),
            ]));
        }
    }
    let errors = op
        .responses
        .iter()
        .filter(|r| r.status.is_success() == Some(false))
        .chain(default);
    for r in errors {
        members.push(result_member(vec![
            ("ok", Type::Literal(Literal::Boolean(false))),
            ("kind", Type::string_literal("http")),
            ("documented", Type::Literal(Literal::Boolean(true))),
            ("status", status_type(r.status)),
            ("error", r.data_type()),
            ("response", response()),
        ]));
    }
    if !(default.is_some() && successes.is_empty()) {
        members.push(result_member(vec![
            ("ok", Type::Literal(Literal::Boolean(false))),
            ("kind", Type::string_literal("http")),
            ("documented", Type::Literal(Literal::Boolean(false))),
            ("status", Type::Number),
            ("error", Type::Unknown),
            ("response", response()),
        ]));
    }
    members.push(Type::builtin("TransportFailure"));
    // Only drops members of the same shape; the member order is kept.
    let mut out: Vec<Type> = Vec::new();
    for m in members {
        if !out.contains(&m) {
            out.push(m);
        }
    }
    Type::Union(out)
}

fn response_headers_type(op: &Operation) -> Option<Type> {
    let props: Vec<Property> = op
        .responses
        .iter()
        .filter(|r| !r.headers.is_empty())
        .map(|r| {
            Property::new(
                r.status.key(),
                Type::Object(Object {
                    properties: r.headers.clone(),
                    index: None,
                }),
            )
        })
        .collect();
    (!props.is_empty()).then_some(Type::Object(Object {
        properties: props,
        index: None,
    }))
}

/// A type name derived from an operation (`{P}Result`), as naming assigned it (design.md 6.6).
fn derived(op: &Operation, template: &str) -> String {
    op.type_names
        .get(template)
        .unwrap_or_else(|| panic!("{} has no name for {template}", op.id))
        .clone()
}

fn operation_unit(op: &Operation) -> Unit {
    let mut unit = Unit::default();
    let data = derived(op, "{P}Data");
    let responses = derived(op, "{P}Responses");
    let errors = derived(op, "{P}Errors");
    let result = derived(op, "{P}Result");
    let def = derived(op, "{}Def");

    unit.alias(&data, &data_type(op), None);
    let succ: Vec<&Response> = op
        .responses
        .iter()
        .filter(|r| r.status.is_success() == Some(true))
        .collect();
    let errs: Vec<&Response> = op
        .responses
        .iter()
        .filter(|r| r.status.is_success() != Some(true))
        .collect();
    if let Some(event) = op.type_names.get("{P}Event") {
        let events = op
            .responses
            .iter()
            .flat_map(|r| &r.contents)
            .filter_map(|c| c.events.as_ref())
            .map(|e| e.ty.clone())
            .collect();
        unit.alias(event, &Type::union(events), None);
    }
    if let Some(item) = op.type_names.get("{P}Item") {
        let items = op
            .responses
            .iter()
            .flat_map(|r| &r.contents)
            .filter_map(|c| c.items.as_ref())
            .map(|i| i.ty.clone())
            .collect();
        unit.alias(item, &Type::union(items), None);
    }
    unit.alias(&responses, &status_map(&succ), None);
    unit.alias(&errors, &status_map(&errs), None);
    if let Some(h) = response_headers_type(op) {
        unit.alias(&derived(op, "{P}ResponseHeaders"), &h, None);
    }
    unit.alias(&result, &result_type(op), None);
    unit.client_types.insert("TransportFailure");

    // OperationDef. `satisfies OperationDef` is not added because it prevents isolatedDeclarations
    // from inferring the type. The shape is checked by the parameter type of `client.request`.
    unit.raw(&format!(
        "export const {def} = {} as const;\n",
        operation_def(op)
    ));
    unit.declares.push(def.clone());
    unit.has_values = true;

    // Call function.
    let mut code = String::new();
    if let Some(doc) = &op.doc {
        code.push_str(&print_doc(doc, 0));
    }
    let optional = if op.has_required_input() { "" } else { "?" };
    writeln!(code, "export function {}<Ctx>(", op.name).unwrap();
    writeln!(code, "  client: Client<Ctx>,").unwrap();
    writeln!(code, "  options{optional}: {data} & RequestOptions<Ctx>,").unwrap();
    writeln!(code, "): Promise<{result}> {{").unwrap();
    writeln!(code, "  return client.request<{result}>({def}, options);").unwrap();
    writeln!(code, "}}").unwrap();
    unit.raw(&code);
    unit.declares.push(op.name.clone());
    unit.client_types.insert("Client");
    unit.client_types.insert("RequestOptions");

    for cb in &op.callbacks {
        for cop in &cb.operations {
            let u = message_unit(cop, "Callback");
            unit.raw(&u.code);
            unit.declares.extend(u.declares);
            unit.refs.extend(u.refs);
            unit.externals.extend(u.externals);
        }
    }
    unit
}

/// Webhooks and callbacks. Only emits the types of the incoming request and the response to return.
fn message_unit(op: &Operation, suffix: &str) -> Unit {
    let mut unit = Unit::default();
    let mut doc = op.doc.clone().unwrap_or_default();
    doc.tag("see", format!("{} {}", op.method, op.path));
    let request = derived(op, &format!("{{P}}{suffix}Request"));
    unit.alias(&request, &data_type(op), Some(&doc));
    let all: Vec<&Response> = op.responses.iter().collect();
    let responses = derived(op, &format!("{{P}}{suffix}Responses"));
    unit.alias(&responses, &status_map(&all), None);
    unit
}

fn js_string_array(items: &[String]) -> String {
    let parts: Vec<String> = items.iter().map(|s| string_literal(s)).collect();
    format!("[{}]", parts.join(", "))
}

fn param_def(p: &Param) -> String {
    let mut fields = Vec::new();
    if let Some(s) = &p.style {
        fields.push(format!("style: {}", string_literal(s)));
    }
    if let Some(e) = p.explode {
        fields.push(format!("explode: {e}"));
    }
    if p.allow_reserved {
        fields.push("allowReserved: true".to_owned());
    }
    if let Some(ct) = &p.content_type {
        fields.push(format!("contentType: {}", string_literal(ct)));
    }
    if fields.is_empty() {
        "{}".to_owned()
    } else {
        format!("{{ {} }}", fields.join(", "))
    }
}

fn body_def(body: &Body) -> String {
    let mut s = String::from("{\n");
    if body.required {
        s.push_str("    required: true,\n");
    }
    s.push_str("    contents: {\n");
    for c in &body.contents {
        let mut fields = Vec::new();
        if !c.encoding.is_empty() {
            let encs: Vec<String> = c
                .encoding
                .iter()
                .map(|e| {
                    let mut f = Vec::new();
                    if let Some(ct) = &e.content_type {
                        f.push(format!("contentType: {}", string_literal(ct)));
                    }
                    if let Some(st) = &e.style {
                        f.push(format!("style: {}", string_literal(st)));
                    }
                    if let Some(ex) = e.explode {
                        f.push(format!("explode: {ex}"));
                    }
                    format!("{}: {{ {} }}", property_key(&e.property), f.join(", "))
                })
                .collect();
            fields.push(format!("encoding: {{ {} }}", encs.join(", ")));
        }
        let inner = if fields.is_empty() {
            "{}".to_owned()
        } else {
            format!("{{ {} }}", fields.join(", "))
        };
        writeln!(s, "      {}: {inner},", property_key(&c.media_type)).unwrap();
    }
    s.push_str("    },\n  }");
    s
}

fn response_def(r: &Response) -> String {
    let kinds: BTreeSet<&str> = r.contents.iter().map(parse_as).collect();
    let first = r.contents.first().map_or(BodyKind::None.as_str(), parse_as);
    let mut fields = vec![format!("parseAs: '{first}'")];
    if kinds.len() > 1 {
        let map: Vec<String> = r
            .contents
            .iter()
            .map(|c| format!("{}: '{}'", property_key(&c.media_type), parse_as(c)))
            .collect();
        fields.push(format!("contentTypes: {{ {} }}", map.join(", ")));
    }
    match r
        .contents
        .iter()
        .find_map(|c| c.events.as_ref()?.json.as_ref())
    {
        Some(JsonEvents::All) => fields.push("jsonEvents: true".to_owned()),
        Some(JsonEvents::Named(names)) => {
            fields.push(format!("jsonEvents: {}", js_string_array(names)));
        }
        None => {}
    }
    format!("{{ {} }}", fields.join(", "))
}

fn operation_def(op: &Operation) -> String {
    let mut s = String::from("{\n");
    writeln!(s, "  v: {OPERATION_DEF_VERSION},").unwrap();
    writeln!(s, "  id: {},", string_literal(&op.id)).unwrap();
    writeln!(s, "  method: {},", string_literal(&op.method)).unwrap();
    writeln!(s, "  path: {},", string_literal(&op.path)).unwrap();
    if !op.tags.is_empty() {
        writeln!(s, "  tags: {},", js_string_array(&op.tags)).unwrap();
    }
    if !op.params.is_empty() {
        s.push_str("  params: {\n");
        for location in [
            ParamIn::Path,
            ParamIn::Query,
            ParamIn::Header,
            ParamIn::Cookie,
        ] {
            let ps: Vec<&Param> = op
                .params
                .iter()
                .filter(|p| p.location == location)
                .collect();
            if ps.is_empty() {
                continue;
            }
            let fields: Vec<String> = ps
                .iter()
                .map(|p| format!("{}: {}", property_key(&p.name), param_def(p)))
                .collect();
            writeln!(s, "    {}: {{ {} }},", location.group(), fields.join(", ")).unwrap();
        }
        if let Some(qs) = op
            .params
            .iter()
            .find(|p| p.location == ParamIn::QueryString)
        {
            let ct = qs
                .content_type
                .as_deref()
                .unwrap_or("application/x-www-form-urlencoded");
            writeln!(
                s,
                "    querystring: {{ contentType: {} }},",
                string_literal(ct)
            )
            .unwrap();
        }
        s.push_str("  },\n");
    }
    if let Some(body) = &op.body {
        writeln!(s, "  body: {},", body_def(body)).unwrap();
    }
    s.push_str("  responses: {\n");
    for r in &op.responses {
        writeln!(
            s,
            "    {}: {},",
            property_key(&r.status.key()),
            response_def(r)
        )
        .unwrap();
    }
    s.push_str("  },\n");
    if !op.security.is_empty() {
        let alternatives: Vec<String> = op
            .security
            .iter()
            .map(|alt| {
                let uses: Vec<String> = alt.iter().map(security_use).collect();
                format!("[{}]", uses.join(", "))
            })
            .collect();
        writeln!(s, "  security: [{}],", alternatives.join(", ")).unwrap();
    }
    s.push('}');
    s
}

fn security_use(u: &tsurara_sem::operation::SecurityUse) -> String {
    let mut fields = vec![
        format!("scheme: {}", string_literal(&u.scheme)),
        format!("type: {}", string_literal(&u.kind)),
    ];
    if let Some(l) = &u.location {
        fields.push(format!("in: {}", string_literal(l)));
    }
    if let Some(n) = &u.name {
        fields.push(format!("name: {}", string_literal(n)));
    }
    if let Some(h) = &u.http_scheme {
        fields.push(format!("httpScheme: {}", string_literal(h)));
    }
    if !u.scopes.is_empty() {
        fields.push(format!("scopes: {}", js_string_array(&u.scopes)));
    }
    format!("{{ {} }}", fields.join(", "))
}

fn server_url_type(server: &Server) -> Type {
    if server.variables.is_empty() || !server.url.contains('{') {
        return Type::string_literal(server.url.clone());
    }
    // Turns `https://{env}.example.com` into a template literal type.
    let mut code = String::from("`");
    let mut rest = server.url.as_str();
    while let Some(start) = rest.find('{') {
        let Some(end) = rest[start..].find('}') else {
            break;
        };
        code.push_str(&escape_template(&rest[..start]));
        let name = &rest[start + 1..start + end];
        let var = server.variables.iter().find(|v| v.name == name);
        let inner = match var {
            Some(v) if !v.values.is_empty() => {
                let lits: Vec<String> = v.values.iter().map(|x| string_literal(x)).collect();
                lits.join(" | ")
            }
            _ => "string".to_owned(),
        };
        write!(code, "${{{inner}}}").unwrap();
        rest = &rest[start + end + 1..];
    }
    code.push_str(&escape_template(rest));
    code.push('`');
    Type::External(tsurara_sem::ir::External { code, import: None })
}

pub(crate) fn escape_template(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('`', "\\`")
        .replace("${", "\\${")
}

fn client_unit(servers: &[Server], security_schemes: &[String]) -> Unit {
    let mut unit = Unit::default();
    if !security_schemes.is_empty() {
        let names: Vec<Type> = security_schemes
            .iter()
            .map(|n| Type::string_literal(n.clone()))
            .collect();
        let doc = Doc {
            description: Some(
                "The security schemes of the API, as the `auth` option of the client receives them (`scheme.scheme`)."
                    .into(),
            ),
            tags: Vec::new(),
        };
        unit.alias("SecuritySchemeName", &Type::Union(names), Some(&doc));
    }
    let mut members: Vec<Type> = servers.iter().map(server_url_type).collect();
    members.push(Type::External(tsurara_sem::ir::External {
        code: "(string & {})".to_owned(),
        import: None,
    }));
    let doc = Doc {
        description: Some(
            "The base URL of the API. The servers in the definition are suggested, and any URL is accepted."
                .into(),
        ),
        tags: Vec::new(),
    };
    unit.alias("BaseUrl", &Type::Union(members), Some(&doc));
    let mut code = String::from(if servers.is_empty() {
        "export const servers = ["
    } else {
        "export const servers = [\n"
    });
    for s in servers {
        let mut fields = vec![format!("url: {}", string_literal(&s.url))];
        if let Some(d) = &s.description {
            fields.push(format!("description: {}", string_literal(d)));
        }
        if !s.variables.is_empty() {
            let vars: Vec<String> = s
                .variables
                .iter()
                .map(|v| {
                    let mut f = vec![format!("default: {}", string_literal(&v.default))];
                    if !v.values.is_empty() {
                        f.push(format!("enum: {}", js_string_array(&v.values)));
                    }
                    format!("{}: {{ {} }}", property_key(&v.name), f.join(", "))
                })
                .collect();
            fields.push(format!("variables: {{ {} }}", vars.join(", ")));
        }
        writeln!(code, "  {{ {} }},", fields.join(", ")).unwrap();
    }
    code.push_str("] as const;\n");
    unit.raw(&code);
    unit.declares.push("servers".to_owned());
    unit.has_values = true;
    unit
}

fn operations_map_unit(ops: &[Operation]) -> Unit {
    let mut unit = Unit::default();
    // Explicit type annotation for isolatedDeclarations.
    let mut ty = String::from("{\n");
    let mut value = String::from("{\n");
    for op in ops {
        let def = derived(op, "{}Def");
        writeln!(ty, "  readonly {}: typeof {def};", property_key(&op.id)).unwrap();
        writeln!(value, "  {}: {def},", property_key(&op.id)).unwrap();
        unit.value_refs.insert(def);
    }
    ty.push('}');
    value.push('}');
    let code = format!("export const operations: {ty} = {value};\n");
    unit.raw(&code);
    unit.declares.push("operations".to_owned());
    unit.has_values = true;
    unit
}

fn paths_map_unit(ops: &[Operation]) -> Unit {
    let mut unit = Unit::default();
    let mut paths: Vec<(String, Vec<Property>)> = Vec::new();
    for op in ops {
        let entry = Type::Object(Object {
            properties: vec![
                Property::new("data", Type::Ref(derived(op, "{P}Data"))),
                Property::new("result", Type::Ref(derived(op, "{P}Result"))),
            ],
            index: None,
        });
        let prop = Property::new(op.method.to_lowercase(), entry);
        match paths.iter_mut().find(|(k, _)| *k == op.path) {
            Some((_, v)) => v.push(prop),
            None => paths.push((op.path.clone(), vec![prop])),
        }
    }
    let ty = Type::Object(Object {
        properties: paths
            .into_iter()
            .map(|(k, v)| {
                Property::new(
                    k,
                    Type::Object(Object {
                        properties: v,
                        index: None,
                    }),
                )
            })
            .collect(),
        index: None,
    });
    unit.alias("Paths", &ty, None);
    unit
}

/// Relative specifier from the file `from` to the file `to`.
pub(crate) fn relative(from: &str, to: &str, ext: &str) -> String {
    let from_dir: Vec<&str> = from.split('/').collect::<Vec<_>>();
    let from_dir = &from_dir[..from_dir.len() - 1];
    let to_parts: Vec<&str> = to.split('/').collect();
    let common = from_dir
        .iter()
        .zip(to_parts.iter())
        .take_while(|(a, b)| a == b)
        .count();
    let mut s = String::new();
    let ups = from_dir.len() - common;
    if ups == 0 {
        s.push_str("./");
    } else {
        for _ in 0..ups {
            s.push_str("../");
        }
    }
    s.push_str(&to_parts[common..].join("/"));
    let stem = s.strip_suffix(".ts").unwrap_or(&s).to_owned();
    format!("{stem}{ext}")
}

/// Import specifier of an external type. Specifiers starting with `.` are relative to the output root.
fn external_specifier(file: &str, from: &str) -> String {
    if !from.starts_with('.') {
        return from.to_owned();
    }
    let depth = file.matches('/').count();
    let trimmed = from.strip_prefix("./").unwrap_or(from);
    if depth == 0 {
        if trimmed.starts_with("../") {
            trimmed.to_owned()
        } else {
            format!("./{trimmed}")
        }
    } else {
        format!("{}{trimmed}", "../".repeat(depth))
    }
}

pub(crate) fn render_file(
    path: &str,
    units: &[Unit],
    type_files: &BTreeMap<String, String>,
    value_files: &BTreeMap<String, String>,
    opts: &Options,
) -> String {
    let ext = opts.import_extension.suffix();
    let declared: BTreeSet<&str> = units
        .iter()
        .flat_map(|u| u.declares.iter().map(String::as_str))
        .collect();
    let mut type_imports: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    let mut value_imports: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    let mut client_types: BTreeSet<&str> = BTreeSet::new();
    let mut client_values: BTreeSet<&str> = BTreeSet::new();
    for u in units {
        for r in &u.refs {
            if declared.contains(r.as_str()) {
                continue;
            }
            if let Some(file) = type_files.get(r) {
                type_imports
                    .entry(relative(path, file, ext))
                    .or_default()
                    .insert(r.clone());
            }
        }
        for r in &u.value_refs {
            if declared.contains(r.as_str()) {
                continue;
            }
            if let Some(file) = value_files.get(r) {
                value_imports
                    .entry(relative(path, file, ext))
                    .or_default()
                    .insert(r.clone());
            }
        }
        for e in &u.externals {
            type_imports
                .entry(external_specifier(path, &e.from))
                .or_default()
                .insert(e.name.clone());
        }
        client_types.extend(u.client_types.iter().copied());
        client_values.extend(u.client_values.iter().copied());
    }
    let mut s = String::new();
    s.push_str(HEADER);
    s.push('\n');
    let mut imports = String::new();
    if !client_values.is_empty() {
        let mut names: Vec<String> = client_types.iter().map(|t| format!("type {t}")).collect();
        names.extend(client_values.iter().map(|v| (*v).to_owned()));
        // Sorted by name, as Biome orders named imports.
        names.sort_by(|a, b| {
            a.trim_start_matches("type ")
                .cmp(b.trim_start_matches("type "))
        });
        writeln!(
            imports,
            "import {{ {} }} from {};",
            names.join(", "),
            string_literal(&opts.client_module)
        )
        .unwrap();
    } else if !client_types.is_empty() {
        let names: Vec<&str> = client_types.into_iter().collect();
        writeln!(
            imports,
            "import type {{ {} }} from {};",
            names.join(", "),
            string_literal(&opts.client_module)
        )
        .unwrap();
    }
    let mut specifiers: BTreeSet<&String> = type_imports.keys().collect();
    specifiers.extend(value_imports.keys());
    for spec in specifiers {
        if let Some(names) = value_imports.get(spec) {
            let names: Vec<&str> = names.iter().map(String::as_str).collect();
            writeln!(
                imports,
                "import {{ {} }} from {};",
                names.join(", "),
                string_literal(spec)
            )
            .unwrap();
        }
        if let Some(names) = type_imports.get(spec) {
            let names: Vec<&str> = names.iter().map(String::as_str).collect();
            writeln!(
                imports,
                "import type {{ {} }} from {};",
                names.join(", "),
                string_literal(spec)
            )
            .unwrap();
        }
    }
    if !imports.is_empty() {
        s.push('\n');
        s.push_str(&imports);
    }
    for u in units {
        s.push('\n');
        s.push_str(&u.code);
    }
    s
}

fn barrel(files: &BTreeMap<String, Vec<Unit>>, opts: &Options, client: bool) -> String {
    let ext = opts.import_extension.suffix();
    let mut s = String::new();
    s.push_str(HEADER);
    s.push('\n');
    if client {
        writeln!(s, "{CLIENT_RANGE_PREFIX}{}", opts.client_version_range).unwrap();
    }
    s.push('\n');
    for (path, units) in files {
        if path == "index.ts" {
            continue;
        }
        let spec = relative("index.ts", path, ext);
        if units.iter().any(|u| u.has_values) {
            writeln!(s, "export * from {};", string_literal(&spec)).unwrap();
        } else {
            writeln!(s, "export type * from {};", string_literal(&spec)).unwrap();
        }
    }
    s
}

