fn files(set: &DocumentSet) -> Vec<(String, String)> {
    generate(set, &Options::default(), &PythonOptions::default())
        .unwrap()
        .files
        .into_iter()
        .map(|f| (f.path, f.contents))
        .collect()
}

fn write_package(dir: &Path, package: &str, files: &[(String, String)]) {
    for (path, contents) in files {
        let full = dir.join(package).join(path);
        std::fs::create_dir_all(full.parent().unwrap()).unwrap();
        std::fs::write(full, contents).unwrap();
    }
}

#[test]
fn generated_modules_look_like_python() {
    let set = DocumentSet::from_value(parse_document(PETS.as_bytes()).unwrap());
    let files = files(&set);
    let pet = &files.iter().find(|(p, _)| p == "pet.py").unwrap().1;
    for line in [
        "# Generated by tsurara. Do not edit.",
        "from __future__ import annotations",
        "@dataclass(kw_only=True)",
        "class Pet:",
        "    id: int",
        "    created_at: str | None = None",
        "    nickname: str | None | Missing = MISSING",
        "    kind: Kind | str",
        "    class_: str | None = None",
        "    parent: Pet | None = None",
        "if TYPE_CHECKING:",
        "    from .owner import Owner",
    ] {
        assert!(pet.contains(line), "missing `{line}` in:\n{pet}");
    }
    let kind = &files.iter().find(|(p, _)| p == "kind.py").unwrap().1;
    assert!(
        kind.contains("class Kind(Enum):\n    CAT = \"cat\"\n    DOG = \"dog\"\n"),
        "{kind}"
    );
    let init = &files.iter().find(|(p, _)| p == "__init__.py").unwrap().1;
    assert!(init.contains("from .pet import Pet\n"), "{init}");
}

#[test]
fn the_corpus_passes_pyright() {
    let checker = PythonChecker {
        package: "api".into(),
    };
    for name in FIXTURES {
        if let Err(e) = checker.check(&files(&fixture(name))) {
            panic!("{name}: {e}");
        }
    }
    let set = DocumentSet::from_value(parse_document(PETS.as_bytes()).unwrap());
    checker.check(&files(&set)).unwrap();
}

const CONSTRUCT: &str = r#"
import dataclasses, enum, importlib, pkgutil, sys
package = importlib.import_module(sys.argv[1])
count = 0
for info in pkgutil.iter_modules(package.__path__):
    module = importlib.import_module(f"{sys.argv[1]}.{info.name}")
    for value in vars(module).values():
        if dataclasses.is_dataclass(value) and value.__module__ == module.__name__:
            required = {
                f.name: None
                for f in dataclasses.fields(value)
                if f.default is dataclasses.MISSING and f.default_factory is dataclasses.MISSING
            }
            value(**required)
            count += 1
print(count)
"#;

#[test]
fn every_module_imports_and_every_dataclass_constructs() {
    let Some(python) = python_or_skip() else {
        return;
    };
    let pets = DocumentSet::from_value(parse_document(PETS.as_bytes()).unwrap());
    let mut sets: Vec<(String, DocumentSet)> = FIXTURES
        .iter()
        .map(|n| (n.to_string(), fixture(n)))
        .collect();
    sets.push(("pets".into(), pets));
    for (name, set) in sets {
        let dir = tempfile::tempdir().unwrap();
        write_package(dir.path(), "api", &files(&set));
        std::fs::write(dir.path().join("construct.py"), CONSTRUCT).unwrap();
        let out = Command::new(&python)
            .args(["construct.py", "api"])
            .current_dir(dir.path())
            .output()
            .unwrap();
        assert!(
            out.status.success(),
            "{name}: {}",
            String::from_utf8_lossy(&out.stderr)
        );
        let count: usize = String::from_utf8_lossy(&out.stdout).trim().parse().unwrap();
        // Some fixtures have no object schemas.
        assert!(count > 0 || name != "pets", "{name}");
    }
}

#[test]
fn the_emitted_type_defs_convert_recursive_and_cross_module_values() {
    let Some(python) = python_or_skip() else {
        return;
    };
    let set = DocumentSet::from_value(parse_document(PETS.as_bytes()).unwrap());
    let dir = tempfile::tempdir().unwrap();
    write_package(dir.path(), "api", &files(&set));
    let out = Command::new(&python)
        .args([
            "-c",
            "import json; from api._typedefs import TYPE_DEFS; print(json.dumps(TYPE_DEFS))",
        ])
        .current_dir(dir.path())
        .output()
        .unwrap();
    assert!(
        out.status.success(),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
    let doc: Value = serde_json::from_slice(&out.stdout).unwrap();
    let defs = Converter::new(&doc);
    let pet = json!({ "ref": "Pet" });
    let input = json!({
        "id": 1,
        "kind": "bird",
        "nickname": null,
        "class": "x",
        "owner": { "name": "o", "pets": [{ "id": 2, "kind": "cat" }] },
        "parent": { "id": 3, "kind": "dog" }
    });
    let value = defs.decode(&pet, &input).unwrap();
    assert_eq!(
        value,
        json!({
            "$type": "Pet",
            "id": 1,
            "kind": { "$unknown": "bird" },
            "nickname": null,
            "class_": "x",
            "owner": { "$type": "Owner", "name": "o", "pets": [{ "$type": "Pet", "id": 2, "kind": "cat" }] },
            "parent": { "$type": "Pet", "id": 3, "kind": "dog" }
        })
    );
    assert_eq!(defs.encode(&pet, &value), input);
}
