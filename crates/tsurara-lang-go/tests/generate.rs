use tsurara_lang_go::{GoOptions, generate};
use tsurara_loader::{DocumentSet, Fetcher, MemoryFetcher, parse_document};
use tsurara_sem::Options;
use tsurara_testkit::{Checker, GoChecker, repo_root};

fn fixture(path: &std::path::Path) -> DocumentSet {
    let name = path.file_name().unwrap().to_string_lossy();
    let url = url::Url::parse(&format!("https://example.com/{name}")).unwrap();
    let mut f = MemoryFetcher::new();
    f.insert(url.as_str(), std::fs::read(path).unwrap());
    let mut set = DocumentSet::load(&url, &f as &dyn Fetcher).unwrap();
    tsurara_loader::normalize_swagger2(&mut set).unwrap();
    set
}

fn options() -> GoOptions {
    GoOptions {
        package: "api".into(),
        ..GoOptions::default()
    }
}

fn files(set: &DocumentSet) -> Vec<(String, String)> {
    generate(set, &Options::default(), &options())
        .unwrap()
        .files
        .into_iter()
        .map(|f| (f.path, f.contents))
        .collect()
}

#[test]
fn fixtures_and_edge_cases_build_cleanly() {
    let mut paths: Vec<std::path::PathBuf> = ["kitchen-sink.yaml", "petstore3.json"]
        .iter()
        .map(|f| {
            repo_root()
                .join("crates/tsurara-lang-typescript/tests/fixtures")
                .join(f)
        })
        .collect();
    let mut edge: Vec<_> = std::fs::read_dir(repo_root().join("corpus/edge-cases"))
        .unwrap()
        .map(|e| e.unwrap().path())
        .collect();
    edge.sort();
    paths.extend(edge);
    let mut failures = Vec::new();
    for path in paths {
        let files = files(&fixture(&path));
        assert!(
            files.iter().all(|(p, c)| p.ends_with("_gen.go")
                && c.starts_with("// Code generated by tsurara. DO NOT EDIT.\n")),
            "{}",
            path.display()
        );
        if let Err(e) = GoChecker::default().check(&files) {
            failures.push(format!("{}: {e}", path.display()));
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n\n"));
}

