#[test]
fn operations_keep_their_names_and_files_and_comments_start_with_them() {
    let set = DocumentSet::from_value(parse_document(NAMES.as_bytes()).unwrap());
    let files = files(&set);
    let all: String = files.iter().map(|(_, c)| c.as_str()).collect();
    let paths: Vec<&str> = files.iter().map(|(p, _)| p.as_str()).collect();
    // The function keeps the operation's name; the schema it collides with moves aside, as the
    // body of that operation (`Body`) or otherwise (`Model`).
    assert!(all.contains("func ToggleAll(ctx context.Context, c *tsurara.Client, body ToggleAllBody, opts *ToggleAllOptions)"), "{all}");
    assert!(all.contains("type ToggleAllBody struct"), "{all}");
    assert!(all.contains("func Status(ctx"), "{all}");
    assert!(all.contains("type StatusModel struct"), "{all}");
    assert!(paths.contains(&"toggle_all_op_gen.go"), "{paths:?}");
    // A numbered name keeps the separator before `_op`.
    assert!(all.contains("func GetX2("), "{all}");
    assert!(paths.contains(&"get_x2_op_gen.go"), "{paths:?}");
    // Doc comments start with the function's name (golint, revive).
    assert!(
        all.contains(
            "// ToggleAll calls POST /todos/toggle.\n//\n// Toggle all todos\nfunc ToggleAll("
        ),
        "{all}"
    );
    assert!(all.contains("// GetX calls GET /x.\nfunc GetX("), "{all}");
    GoChecker::default().check(&files).unwrap();
}

