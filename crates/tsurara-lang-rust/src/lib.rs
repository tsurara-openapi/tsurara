//! The Rust backend (docs/languages/rust.md): serde structs and enums for the runtime crate
//! `tsurara-client` (`runtimes/rust`), and async call functions. Experimental.

pub mod external;
mod mocks;
pub mod naming;
mod operations;
mod print;
mod vendor;

/// The crates a vendored runtime needs in the user's `Cargo.toml` (`runtime: vendor`), with or
/// without the client layer.
pub fn vendored_dependencies(client: bool) -> Vec<&'static str> {
    vendor::dependencies(client)
}

use tsurara_backend::{Backend, Emitted, Error, Markers};
use tsurara_lower::{Capabilities, Enums, Inheritance, lower};
use tsurara_sem::{Model, Options};

/// The first line of every generated file.
pub const HEADER: &str = "// Generated by tsurara. Do not edit.";

/// The version of `tsurara-client` the generated code needs, recorded in `mod.rs` for `tsurara check`.
pub const RUNTIME_REQUIREMENT: &str = "^0.1.0";

/// What Rust can express (design.md 18.5.2, docs/languages/rust.md).
pub const CAPABILITIES: Capabilities = Capabilities {
    inline_records: false,
    structural_unions: false,
    tagged_unions: true,
    intersections: false,
    inheritance: Inheritance::None,
    literal_types: false,
    enums: Enums::Any,
    tuples: true,
    strict_decoding: true,
    nullable_primitives: true,
    recursion_by_value: false,
};

/// Options of the `rust` section.
#[derive(Debug, Clone)]
pub struct RustOptions {
    /// The path generated code uses for the runtime crate.
    pub runtime_crate: String,
    /// Emit mock factories and routes under `mocks/` (`rust.mocks`).
    pub mocks: bool,
}

impl Default for RustOptions {
    fn default() -> Self {
        RustOptions {
            runtime_crate: "tsurara_client".into(),
            mocks: false,
        }
    }
}

#[derive(Debug, Clone, Default)]
pub struct Rust {
    pub options: RustOptions,
}

impl Backend for Rust {
    fn id(&self) -> &'static str {
        "rust"
    }

    fn markers(&self) -> Markers {
        Markers {
            generated: HEADER.to_owned(),
            version: Some(tsurara_backend::VersionMarker {
                file: "mod.rs".into(),
                prefix: "// Requires tsurara-client ".into(),
            }),
            sidecars: Vec::new(),
        }
    }

    fn emit(&self, model: &Model, opts: &Options) -> Result<Emitted, Error> {
        if opts.runtime == tsurara_sem::RuntimeSource::Vendor
            && self.options.runtime_crate == RustOptions::default().runtime_crate
        {
            return Err(Error::Options(
                "`runtime: vendor` needs `rust.runtimeCrate`: the path of the vendored module `runtime` in your crate, such as `crate::api::runtime`".into(),
            ));
        }
        let (module, mut warnings) = lower(model, &CAPABILITIES);
        let (files, more, manifest) = print::print(model, &module, opts, &self.options);
        warnings.extend(more);
        Ok(Emitted {
            files,
            warnings,
            manifest: Some(manifest),
        })
    }

    fn options_json(&self) -> serde_json::Value {
        serde_json::json!({ "runtimeCrate": self.options.runtime_crate, "mocks": self.options.mocks })
    }

    fn example(&self, input: &tsurara_backend::ExampleInput) -> Option<tsurara_backend::Example> {
        operations::example(input, &self.options.runtime_crate)
    }
}

/// Builds the model from a loaded definition and generates Rust.
pub fn generate(
    set: &tsurara_loader::DocumentSet,
    opts: &Options,
    rust: &RustOptions,
) -> Result<tsurara_backend::Output, Error> {
    let backend = Rust {
        options: rust.clone(),
    };
    tsurara_backend::generate(&backend, set, opts)
}
