//! Runs the `tsurara` binary on configuration files in a temporary directory.

use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use std::time::{Duration, SystemTime};

const HEADER: &str = "// Generated by tsurara. Do not edit.";

const OPENAPI: &str = r##"
openapi: 3.1.0
info: { title: pets, version: "1" }
paths:
  /pets/{id}:
    get:
      operationId: getPet
      tags: [pet]
      parameters:
        - { name: id, in: path, required: true, schema: { type: string } }
      responses:
        "200":
          description: ok
          content:
            application/json:
              schema: { $ref: "#/components/schemas/Pet" }
components:
  schemas:
    Pet:
      type: object
      required: [id]
      properties:
        id: { type: string }
"##;

/// A schema with `not`, which produces a warning.
const OPENAPI_WITH_WARNING: &str = r##"
openapi: 3.1.0
info: { title: t, version: "1" }
paths: {}
components:
  schemas:
    Name: { type: string, not: { const: "" } }
"##;

fn write(dir: &Path, path: &str, contents: &str) -> PathBuf {
    let path = dir.join(path);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(&path, contents).unwrap();
    path
}

fn tsurara(cwd: &Path, args: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_tsurara"))
        .args(args)
        .current_dir(cwd)
        .env_remove("RUST_LOG")
        .output()
        .unwrap()
}

fn stderr(out: &Output) -> String {
    String::from_utf8_lossy(&out.stderr).into_owned()
}

fn setup(openapi: &str) -> tempfile::TempDir {
    let tmp = tempfile::tempdir().unwrap();
    write(tmp.path(), "api/openapi.yaml", openapi);
    write(
        tmp.path(),
        "tsurara.config.yaml",
        "input: api/openapi.yaml\noutput: src/generated\n",
    );
    tmp
}

fn generated_files(dir: &Path) -> Vec<String> {
    fn walk(root: &Path, dir: &Path, out: &mut Vec<String>) {
        for entry in std::fs::read_dir(dir).unwrap() {
            let path = entry.unwrap().path();
            if path.is_dir() {
                walk(root, &path, out);
            } else {
                let rel = path.strip_prefix(root).unwrap();
                out.push(rel.to_string_lossy().replace('\\', "/"));
            }
        }
    }
    let mut out = Vec::new();
    walk(dir, dir, &mut out);
    out.sort();
    out
}

#[test]
fn generate_writes_the_output_of_the_discovered_config() {
    let tmp = setup(OPENAPI);
    // The configuration is found from a subdirectory too.
    std::fs::create_dir_all(tmp.path().join("api")).unwrap();
    let out = tsurara(&tmp.path().join("api"), &["generate"]);
    assert!(out.status.success(), "{}", stderr(&out));

    let dir = tmp.path().join("src/generated");
    let files = generated_files(&dir);
    assert!(files.iter().any(|f| f == "index.ts"), "{files:?}");
    for f in &files {
        let contents = std::fs::read_to_string(dir.join(f)).unwrap();
        assert!(contents.starts_with(HEADER), "{f} has no header");
    }
    let all: String = files
        .iter()
        .map(|f| std::fs::read_to_string(dir.join(f)).unwrap())
        .collect();
    assert!(all.contains("export type Pet"));
    assert!(all.contains("getPet"));
}

#[test]
fn generate_deletes_stale_files_and_keeps_unchanged_ones() {
    let tmp = setup(OPENAPI);
    let dir = tmp.path().join("src/generated");
    let out = tsurara(tmp.path(), &["generate"]);
    assert!(out.status.success(), "{}", stderr(&out));

    let stale = write(
        &dir,
        "schemas/Old.ts",
        &format!("{HEADER}\nexport type Old = string;\n"),
    );
    let handwritten = write(&dir, "custom.ts", "export const x = 1;\n");
    let index = dir.join("index.ts");
    let old = SystemTime::now() - Duration::from_secs(3600);
    std::fs::File::options()
        .write(true)
        .open(&index)
        .unwrap()
        .set_modified(old)
        .unwrap();

    let out = tsurara(tmp.path(), &["generate"]);
    assert!(out.status.success(), "{}", stderr(&out));
    assert!(!stale.exists(), "stale generated files are deleted");
    assert!(handwritten.exists(), "files without the header are kept");
    let mtime = std::fs::metadata(&index).unwrap().modified().unwrap();
    assert_eq!(mtime, old, "unchanged files are not rewritten");
}

#[test]
fn warnings_are_shown_with_locations_and_strict_fails() {
    let tmp = setup(OPENAPI_WITH_WARNING);
    let out = tsurara(tmp.path(), &["generate"]);
    assert!(out.status.success(), "{}", stderr(&out));
    let err = stderr(&out);
    assert!(err.contains("unsupported"), "{err}");
    assert!(err.contains("#/components/schemas/Name/not"), "{err}");
    // Local files are shown relative to the current directory.
    assert!(
        err.contains(" api/openapi.yaml#/components/schemas/Name/not"),
        "{err}"
    );

    let tmp = setup(OPENAPI_WITH_WARNING);
    let out = tsurara(tmp.path(), &["generate", "--strict"]);
    assert!(!out.status.success());
    assert!(stderr(&out).contains("#/components/schemas/Name/not"));
    assert!(
        !tmp.path().join("src/generated").exists(),
        "nothing is written when --strict fails"
    );
}

#[test]
fn config_and_target_options() {
    let tmp = tempfile::tempdir().unwrap();
    write(tmp.path(), "openapi.yaml", OPENAPI);
    write(
        tmp.path(),
        "conf/my.yaml",
        "input: ../openapi.yaml\ntargets:\n  - { name: a, output: ../out/a }\n  - { name: b, output: ../out/b }\n",
    );
    let out = tsurara(
        tmp.path(),
        &["generate", "--config", "conf/my.yaml", "--target", "b"],
    );
    assert!(out.status.success(), "{}", stderr(&out));
    assert!(tmp.path().join("out/b/index.ts").exists());
    assert!(!tmp.path().join("out/a").exists());

    let out = tsurara(
        tmp.path(),
        &["generate", "--config", "conf/my.yaml", "--target", "c"],
    );
    assert!(!out.status.success());
    assert!(stderr(&out).contains("`c`"), "{}", stderr(&out));
}

#[test]
fn errors_are_reported() {
    let tmp = tempfile::tempdir().unwrap();
    let out = tsurara(tmp.path(), &["generate"]);
    assert!(!out.status.success());
    assert!(stderr(&out).contains("tsurara.config"), "{}", stderr(&out));

    write(
        tmp.path(),
        "tsurara.config.yaml",
        "input: missing.yaml\noutput: out\n",
    );
    let out = tsurara(tmp.path(), &["generate"]);
    assert!(!out.status.success());
    assert!(stderr(&out).contains("missing.yaml"), "{}", stderr(&out));
}

#[test]
fn the_init_template_is_a_valid_configuration_with_its_comments_removed() {
    let dir = tempfile::tempdir().unwrap();
    let out = tsurara(dir.path(), &["init"]);
    assert!(out.status.success(), "{}", stderr(&out));
    let template = std::fs::read_to_string(dir.path().join("tsurara.config.yaml")).unwrap();
    // Uncomment the settings: lines that are `# key: value` or indented ones.
    let uncommented: String = template
        .lines()
        .filter(|l| !l.starts_with("# tsurara") && !l.starts_with("# See"))
        .map(|l| l.strip_prefix("# ").unwrap_or(l))
        .map(|l| format!("{l}\n"))
        .collect();
    write(dir.path(), "tsurara.config.yaml", &uncommented);
    write(dir.path(), "openapi.yaml", OPENAPI);
    let out = tsurara(dir.path(), &["generate"]);
    assert!(out.status.success(), "{}\n{uncommented}", stderr(&out));
}

#[test]
fn the_react_query_preset_generates_query_options_schemas_and_mocks() {
    let dir = tempfile::tempdir().unwrap();
    let out = tsurara(dir.path(), &["init", "--preset", "react-query"]);
    assert!(out.status.success(), "{}", stderr(&out));
    let stdout = String::from_utf8_lossy(&out.stdout);
    for package in ["@tsurara/client", "@tanstack/react-query", "zod", "msw"] {
        assert!(stdout.contains(package), "{stdout}");
    }
    write(dir.path(), "openapi.yaml", OPENAPI);
    let out = tsurara(dir.path(), &["generate"]);
    assert!(out.status.success(), "{}", stderr(&out));
    let files = generated_files(&dir.path().join("src/generated"));
    for dir in ["query/", "zod/", "mocks/"] {
        assert!(
            files.iter().any(|f| f.starts_with(dir)),
            "{dir} in {files:?}"
        );
    }
}

#[test]
fn rust_targets_generate_a_module_and_say_the_backend_is_experimental() {
    let tmp = setup(OPENAPI);
    write(
        tmp.path(),
        "tsurara.config.yaml",
        "input: api/openapi.yaml\noutput: src/api\nlanguage: rust\n",
    );
    let out = tsurara(tmp.path(), &["generate"]);
    assert!(out.status.success(), "{}", stderr(&out));
    assert!(stderr(&out).contains("experimental"), "{}", stderr(&out));
    let files = generated_files(&tmp.path().join("src/api"));
    assert!(files.iter().any(|f| f == "mod.rs"), "{files:?}");
}
