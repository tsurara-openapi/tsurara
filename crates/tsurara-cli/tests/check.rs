#[test]
fn init_writes_a_template_and_does_not_overwrite() {
    let tmp = tempfile::tempdir().unwrap();
    let out = tsurara(tmp.path(), &["init"]);
    assert!(out.status.success(), "{}", all_output(&out));
    let config = tmp.path().join("tsurara.config.yaml");
    let template = std::fs::read_to_string(&config).unwrap();
    assert!(template.contains("input:"), "{template}");
    assert!(template.contains("output:"), "{template}");
    // The template loads once the input exists.
    write(tmp.path(), "openapi.yaml", OPENAPI);
    let generated = tsurara(tmp.path(), &["generate"]);
    assert!(generated.status.success(), "{}", all_output(&generated));

    std::fs::write(&config, "input: x.yaml\noutput: out\n").unwrap();
    let again = tsurara(tmp.path(), &["init"]);
    assert!(!again.status.success());
    assert!(
        all_output(&again).contains("already exists"),
        "{}",
        all_output(&again)
    );
    assert_eq!(
        std::fs::read_to_string(&config).unwrap(),
        "input: x.yaml\noutput: out\n"
    );
    let forced = tsurara(tmp.path(), &["init", "--force"]);
    assert!(forced.status.success(), "{}", all_output(&forced));
    assert_eq!(std::fs::read_to_string(&config).unwrap(), template);
}

#[test]
fn check_runs_the_transform_hooks() {
    if Command::new("node").arg("--version").output().is_err() {
        return;
    }
    let tmp = tempfile::tempdir().unwrap();
    write(tmp.path(), "api/openapi.yaml", OPENAPI);
    write(
        tmp.path(),
        "tsurara.config.yaml",
        "input: api/openapi.yaml\noutput: src/generated\nhooks:\n  transformFiles: [node, stamp.mjs]\n",
    );
    write(
        tmp.path(),
        "stamp.mjs",
        "let s = ''; process.stdin.on('data', (c) => (s += c)); process.stdin.on('end', () => { const files = JSON.parse(s); for (const f of files) f.contents += '// stamped\\n'; process.stdout.write(JSON.stringify(files)); });\n",
    );
    let out = tsurara(tmp.path(), &["generate"]);
    assert!(out.status.success(), "{}", all_output(&out));
    let out = tsurara(tmp.path(), &["check"]);
    assert!(out.status.success(), "{}", all_output(&out));
}

#[test]
fn check_compares_the_rust_runtime_with_cargo_lock() {
    let tmp = tempfile::tempdir().unwrap();
    write(tmp.path(), "api/openapi.yaml", OPENAPI);
    write(
        tmp.path(),
        "tsurara.config.yaml",
        "input: api/openapi.yaml\noutput: src/api\nlanguage: rust\n",
    );
    let out = tsurara(tmp.path(), &["generate"]);
    assert!(out.status.success(), "{}", all_output(&out));
    let lock = |version: &str| {
        format!(
            "version = 4\n\n[[package]]\nname = \"other\"\nversion = \"9.0.0\"\n\n[[package]]\nname = \"tsurara-client\"\nversion = \"{version}\"\n"
        )
    };
    write(tmp.path(), "Cargo.lock", &lock("0.2.0"));
    let out = tsurara(tmp.path(), &["check"]);
    assert_eq!(out.status.code(), Some(1), "{}", all_output(&out));
    let text = all_output(&out);
    assert!(text.contains("tsurara-client 0.2.0"), "{text}");
    assert!(text.contains("^0.1.0"), "{text}");
    write(tmp.path(), "Cargo.lock", &lock("0.1.3"));
    let out = tsurara(tmp.path(), &["check"]);
    assert!(out.status.success(), "{}", all_output(&out));
}

#[test]
fn check_compares_the_go_runtime_with_go_mod() {
    let tmp = tempfile::tempdir().unwrap();
    write(tmp.path(), "api/openapi.yaml", OPENAPI);
    write(
        tmp.path(),
        "tsurara.config.yaml",
        "input: api/openapi.yaml\noutput: internal/api\nlanguage: go\n",
    );
    let out = tsurara(tmp.path(), &["generate"]);
    assert!(out.status.success(), "{}", all_output(&out));
    let module = |require: &str| {
        format!(
            "module example.com/app\n\ngo 1.24\n\nrequire (\n\tgithub.com/other/x v1.0.0\n\t{require}\n)\n"
        )
    };
    write(
        tmp.path(),
        "go.mod",
        &module("github.com/tsurara-openapi/tsurara/runtimes/go v0.2.0"),
    );
    let out = tsurara(tmp.path(), &["check"]);
    assert_eq!(out.status.code(), Some(1), "{}", all_output(&out));
    let text = all_output(&out);
    assert!(
        text.contains("github.com/tsurara-openapi/tsurara/runtimes/go 0.2.0"),
        "{text}"
    );
    write(
        tmp.path(),
        "go.mod",
        &module("github.com/tsurara-openapi/tsurara/runtimes/go v0.1.4 // indirect"),
    );
    let out = tsurara(tmp.path(), &["check"]);
    assert!(out.status.success(), "{}", all_output(&out));
    // A module replaced by a directory is not checked.
    write(
        tmp.path(),
        "go.mod",
        &(module("github.com/tsurara-openapi/tsurara/runtimes/go v0.0.0")
            + "\nreplace github.com/tsurara-openapi/tsurara/runtimes/go => ../tsurara/runtimes/go\n"),
    );
    let out = tsurara(tmp.path(), &["check"]);
    assert!(out.status.success(), "{}", all_output(&out));
    assert!(
        all_output(&out).contains("replaced"),
        "{}",
        all_output(&out)
    );
}

/// `tsurara init --agents` writes the rules for coding agents into `AGENTS.md`, or into `CLAUDE.md`
/// when only that exists, and replaces its own section on later runs.
#[test]
fn init_agents_writes_the_agent_instructions_once() {
    let tmp = tempfile::tempdir().unwrap();
    let out = tsurara(tmp.path(), &["init", "--agents"]);
    assert!(
        out.status.success(),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
    assert!(tmp.path().join("tsurara.config.yaml").exists());
    let agents = std::fs::read_to_string(tmp.path().join("AGENTS.md")).unwrap();
    assert!(agents.contains("tsurara generate"), "{agents}");
    assert!(agents.contains("Do not edit generated files"), "{agents}");

    // Again: the config is kept, and the section is not repeated.
    let again = tsurara(tmp.path(), &["init", "--agents"]);
    assert!(
        again.status.success(),
        "{}",
        String::from_utf8_lossy(&again.stderr)
    );
    let agents2 = std::fs::read_to_string(tmp.path().join("AGENTS.md")).unwrap();
    assert_eq!(agents, agents2);

    // With only CLAUDE.md, the section goes there, after what is already in it.
    let other = tempfile::tempdir().unwrap();
    std::fs::write(other.path().join("CLAUDE.md"), "# Project\n\nOur rules.\n").unwrap();
    let out = tsurara(other.path(), &["init", "--agents"]);
    assert!(out.status.success());
    let claude = std::fs::read_to_string(other.path().join("CLAUDE.md")).unwrap();
    assert!(claude.starts_with("# Project\n\nOur rules.\n"), "{claude}");
    assert!(claude.contains("tsurara check"), "{claude}");
    assert!(!other.path().join("AGENTS.md").exists());
}
