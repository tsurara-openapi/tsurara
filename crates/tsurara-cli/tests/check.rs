//! `tsurara check` and `tsurara init` (design.md chapter 12).

use std::path::{Path, PathBuf};
use std::process::{Command, Output};

const OPENAPI: &str = r##"
openapi: 3.1.0
info: { title: pets, version: "1" }
paths: {}
components:
  schemas:
    Pet: { type: object, properties: { id: { type: string } } }
    Tag: { type: string }
"##;

fn write(dir: &Path, path: &str, contents: &str) -> PathBuf {
    let path = dir.join(path);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(&path, contents).unwrap();
    path
}

fn tsurara(cwd: &Path, args: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_tsurara"))
        .args(args)
        .current_dir(cwd)
        .output()
        .unwrap()
}

fn all_output(out: &Output) -> String {
    format!(
        "{}{}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    )
}

fn generated() -> tempfile::TempDir {
    let tmp = tempfile::tempdir().unwrap();
    write(tmp.path(), "api/openapi.yaml", OPENAPI);
    write(
        tmp.path(),
        "tsurara.config.yaml",
        "input: api/openapi.yaml\noutput: src/generated\n",
    );
    let out = tsurara(tmp.path(), &["generate"]);
    assert!(out.status.success(), "{}", all_output(&out));
    tmp
}

#[test]
fn check_passes_when_the_output_is_up_to_date() {
    let tmp = generated();
    let out = tsurara(tmp.path(), &["check"]);
    assert!(out.status.success(), "{}", all_output(&out));
    assert!(
        all_output(&out).contains("up to date"),
        "{}",
        all_output(&out)
    );
}

#[test]
fn check_fails_after_a_generated_file_is_edited_by_hand() {
    let tmp = generated();
    let pet = tmp.path().join("src/generated/schemas/Pet.ts");
    let edited = std::fs::read_to_string(&pet).unwrap() + "// edited\n";
    std::fs::write(&pet, edited).unwrap();
    std::fs::remove_file(tmp.path().join("src/generated/schemas/Tag.ts")).unwrap();
    write(
        tmp.path(),
        "src/generated/schemas/Old.ts",
        "// Generated by tsurara. Do not edit.\nexport type Old = string;\n",
    );
    write(tmp.path(), "src/generated/handwritten.ts", "export {};\n");
    let out = tsurara(tmp.path(), &["check"]);
    assert_eq!(out.status.code(), Some(1), "{}", all_output(&out));
    let text = all_output(&out);
    assert!(text.contains("changed: schemas/Pet.ts"), "{text}");
    assert!(text.contains("missing: schemas/Tag.ts"), "{text}");
    assert!(text.contains("stale: schemas/Old.ts"), "{text}");
    assert!(!text.contains("handwritten.ts"), "{text}");
    // check writes nothing.
    assert!(!tmp.path().join("src/generated/schemas/Tag.ts").exists());
}

#[test]
fn check_detects_client_version_mismatches() {
    let tmp = generated();
    write(
        tmp.path(),
        "node_modules/@tsurara/client/package.json",
        r#"{ "name": "@tsurara/client", "version": "0.2.0" }"#,
    );
    let out = tsurara(tmp.path(), &["check"]);
    assert_eq!(out.status.code(), Some(1), "{}", all_output(&out));
    let text = all_output(&out);
    assert!(text.contains("@tsurara/client 0.2.0"), "{text}");
    assert!(text.contains("^0.1.0"), "{text}");
    write(
        tmp.path(),
        "node_modules/@tsurara/client/package.json",
        r#"{ "name": "@tsurara/client", "version": "0.1.7" }"#,
    );
    let out = tsurara(tmp.path(), &["check"]);
    assert!(out.status.success(), "{}", all_output(&out));
}

