import assert from 'node:assert/strict';
import { test } from 'node:test';
import { ts } from '../src/index.ts';

test('imports follow the target and the manifest', () => {
  const f = ts.file('hooks/useGetPet.ts', {
    importExtension: '.js',
    clientModule: '@tsurara/client',
  });
  const fn = f.import({ identifier: 'getPet', file: 'operations/getPet.ts' });
  const data = f.importType({ identifier: 'GetPetData', file: 'operations/getPet.ts' });
  f.importTypeFrom('@tsurara/client', 'Client');
  f.line(`export const x = (c: Client<unknown>, d: ${data}) => ${fn}(c, d);`);
  assert.equal(
    f.render('// Generated by tsurara. Do not edit.'),
    "// Generated by tsurara. Do not edit.\n\nimport type { Client } from '@tsurara/client';\nimport { getPet } from '../operations/getPet.js';\nimport type { GetPetData } from '../operations/getPet.js';\n\nexport const x = (c: Client<unknown>, d: GetPetData) => getPet(c, d);\n",
  );
});

test('casing', () => {
  assert.equal(ts.pascal('getPetById'), 'GetPetById');
  assert.equal(ts.camel('get pet-by id'), 'getPetById');
});
