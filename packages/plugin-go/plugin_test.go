package tsuraraplugin_test

import (
	"bytes"
	"encoding/json"
	"strings"
	"testing"

	tsuraraplugin "github.com/tsurara-openapi/tsurara/packages/plugin-go"
	"github.com/tsurara-openapi/tsurara/packages/plugin-go/protocol"
)

func TestServe(t *testing.T) {
	p := tsuraraplugin.Plugin{
		Name: "files",
		Extend: func(in protocol.ExtendInput) ([]protocol.OutputFile, error) {
			return []protocol.OutputFile{{Path: "a.txt", Contents: in.Marker + "\n"}}, nil
		},
	}
	in := `{"type":"hello","protocol":1}
{"type":"call","stage":"extend","input":{"language":"typescript","model":{},"common":{},"options":null,"marker":"// m"}}
{"type":"call","stage":"transformFiles","input":[]}
`
	var out bytes.Buffer
	if err := tsuraraplugin.Serve(p, strings.NewReader(in), &out); err != nil {
		t.Fatal(err)
	}
	lines := strings.Split(strings.TrimSpace(out.String()), "\n")
	var hello, result, failed map[string]any
	for i, v := range []*map[string]any{&hello, &result, &failed} {
		if err := json.Unmarshal([]byte(lines[i]), v); err != nil {
			t.Fatal(err)
		}
	}
	if hello["name"] != "files" || hello["stages"].([]any)[0] != "extend" {
		t.Fatalf("%v", hello)
	}
	if result["type"] != "result" || !strings.Contains(lines[1], `"contents":"// m\n"`) {
		t.Fatalf("%s", lines[1])
	}
	if failed["type"] != "error" {
		t.Fatalf("%v", failed)
	}
}

func TestFile(t *testing.T) {
	f := tsuraraplugin.NewFile("extra/x_gen.go", "api")
	f.Import("context", "")
	f.Line("var _ = context.Background")
	got, err := f.Render("// Code generated by tsurara. DO NOT EDIT.")
	if err != nil {
		t.Fatal(err)
	}
	want := "// Code generated by tsurara. DO NOT EDIT.\n\npackage api\n\nimport (\n\t\"context\"\n)\n\nvar _ = context.Background\n"
	if got != want {
		t.Fatalf("%q", got)
	}
}
